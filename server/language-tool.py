    def check_text(self, text: str) -> List[Dict[str, Any]]:
        """
        Проверяет текст на грамматические и стилистические ошибки
        
        Args:
            text: Текст для проверки
            
        Returns:
            List[Dict]: Список найденных ошибок с описанием и предложениями исправлений
        """
        if not text:
            return []
        
        results = []
        
        # Сначала добавим общие проверки (для слов, которых нет в списке)
        
        # Проверка на "жи", "ши" в словах, где это не проверено целиком
        for match in re.finditer(r'\b\w*[жш]ы\w*\b', text, re.IGNORECASE):
            word = match.group(0)
            improved = re.sub(r'([жш])ы', r'\1и', word, flags=re.IGNORECASE)
            
            start = max(0, match.start() - 20)
            end = min(len(text), match.end() + 20)
            context = text[start:end].strip()
            
            # Применяем исправление к контексту
            improved_context = context.replace(word, improved)
            
            # Формируем результат
            result = {
                "original": context,
                "improved": improved_context,
                "explanation": f'После букв "ж" и "ш" пишется "и", а не "ы". Правильно: "{improved}"',
                "severity": "high"
            }
            results.append(result)
            
        # Проверка на "ча", "ща" в словах, где это не проверено целиком
        for match in re.finditer(r'\b\w*[чщ]я\w*\b', text, re.IGNORECASE):
            word = match.group(0)
            improved = re.sub(r'([чщ])я', r'\1а', word, flags=re.IGNORECASE)
            
            start = max(0, match.start() - 20)
            end = min(len(text), match.end() + 20)
            context = text[start:end].strip()
            
            # Применяем исправление к контексту
            improved_context = context.replace(word, improved)
            
            # Формируем результат
            result = {
                "original": context,
                "improved": improved_context,
                "explanation": f'После букв "ч" и "щ" пишется "а", а не "я". Правильно: "{improved}"',
                "severity": "high"
            }
            results.append(result)
        
        # Теперь применяем конкретные правила к тексту
        for pattern, replacement, explanation, severity in self.rules:
            # Ищем совпадения с регулярным выражением в тексте
            matches = re.finditer(pattern, text, re.IGNORECASE)
            
