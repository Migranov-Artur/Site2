    def check_text(self, text: str) -> List[Dict[str, Any]]:
        """
        Проверяет текст на грамматические и стилистические ошибки
        
        Args:
            text: Текст для проверки
            
        Returns:
            List[Dict]: Список найденных ошибок с описанием и предложениями исправлений
        """
        if not text:
            return []
        
        results = []
        
        # Применяем каждое правило к тексту
        for pattern, replacement, explanation, severity in self.rules:
            # Ищем совпадения с регулярным выражением в тексте
            matches = re.finditer(pattern, text, re.IGNORECASE)
            
            for match in matches:
                # Получаем часть текста вокруг найденного совпадения для контекста
                start = max(0, match.start() - 20)
                end = min(len(text), match.end() + 20)
                
                # Извлекаем контекст и нормализуем пробелы
                context = text[start:end].strip()
                original = match.group(0)
                
                # Применяем исправление
                improved_text = re.sub(pattern, replacement, context, flags=re.IGNORECASE)
                
                # Формируем результат
                result = {
                    "original": context,
                    "improved": improved_text,
                    "explanation": explanation,
                    "severity": severity
                }
                
                results.append(result)
        
        print(f"Found {len(results)} issues in text", file=sys.stderr)
        return results
    
